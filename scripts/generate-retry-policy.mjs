#!/usr/bin/env node
// Emits the SDK's list of non-idempotent API operations from a bundled
// OpenAPI spec (JSON). Upstream, every POST declares `x-idempotent`;
// `false` marks operations that create a resource without a client-supplied
// idempotency key, so the SDKs must not replay them after a network error
// that may have reached the server. A POST that lacks the annotation is
// treated as non-idempotent, so a forgotten annotation costs a retry, never
// a duplicate. The output language is picked from the output file extension.
//
// Usage: node scripts/generate-retry-policy.mjs <bundled-spec.json> <out.ts|out.py>
import { readFileSync, writeFileSync } from 'node:fs'
import { basename, extname } from 'node:path'

const HTTP_METHODS = ['get', 'put', 'post', 'delete', 'options', 'head', 'patch', 'trace']

const [specPath, outPath] = process.argv.slice(2)
if (!specPath || !outPath) {
  console.error('usage: generate-retry-policy.mjs <bundled-spec.json> <out.ts|out.py>')
  process.exit(2)
}

const spec = JSON.parse(readFileSync(specPath, 'utf8'))

const operations = []
let annotated = 0
for (const [path, item] of Object.entries(spec.paths ?? {})) {
  for (const method of HTTP_METHODS) {
    const operation = item[method]
    if (!operation) continue
    const idempotent = operation['x-idempotent']
    if (idempotent !== undefined) {
      annotated++
    }
    if (idempotent !== undefined && typeof idempotent !== 'boolean') {
      throw new Error(
        `${method.toUpperCase()} ${path}: x-idempotent must be a boolean, got ${JSON.stringify(idempotent)}`
      )
    }
    if (idempotent === false || (method === 'post' && idempotent !== true)) {
      operations.push([method.toUpperCase(), path])
    }
  }
}
operations.sort(([m1, p1], [m2, p2]) => p1.localeCompare(p2) || m1.localeCompare(m2))
if (annotated === 0) {
  throw new Error(
    `${specPath}: no operation declares x-idempotent; the spec pin (spec/runtime-ref) predates the extension`
  )
}

const header = `Generated by scripts/generate-retry-policy.mjs from ${basename(specPath)}. Do not edit.`
const doc = [
  'Operations the API spec marks `x-idempotent: false`, plus any POST it does',
  'not mark `x-idempotent: true`: they may create a resource without a',
  'client-supplied idempotency key, so a request that may already have reached',
  'the server must not be replayed. Paths are OpenAPI templates (`{param}`',
  'matches one segment).',
]

let source
switch (extname(outPath)) {
  case '.ts':
    source = [
      `// ${header}`,
      '',
      '/**',
      ...doc.map((line) => ` * ${line}`),
      ' */',
      'export const NON_IDEMPOTENT_OPERATIONS: readonly (readonly [',
      '  method: string,',
      '  path: string,',
      '])[] = [',
      ...operations.map(([method, path]) => `  ['${method}', '${path}'],`),
      ']',
      '',
    ].join('\n')
    break
  case '.py':
    source = [
      `# ${header}`,
      ...doc.map((line) => `# ${line}`),
      '',
      'from typing import List, Tuple',
      '',
      'NON_IDEMPOTENT_OPERATIONS: List[Tuple[str, str]] = [',
      ...operations.map(([method, path]) => `    ("${method}", "${path}"),`),
      ']',
      '',
    ].join('\n')
    break
  default:
    throw new Error(`unsupported output extension: ${outPath}`)
}

writeFileSync(outPath, source)
